func TestEncryptedProfiles(t *testing.T) {
	dir := t.TempDir()
	write(t, filepath.Join(dir, "10-dns.conf"), "[Resolve]\nDNSOverTLS=yes\n")

	profiles, err := EncryptedProfiles(dir)
	if err != nil {
		t.Fatalf("EncryptedProfiles: %v", err)
	}
	if len(profiles) != 1 {
		t.Fatalf("got %v, want one profile", profiles)
	}
}

func TestEncryptedProfilesAbsent(t *testing.T) {
	profiles, err := EncryptedProfiles(filepath.Join(t.TempDir(), "absent"))
	if err != nil {
		t.Fatalf("a missing directory is not a failure: %v", err)
	}
	if len(profiles) != 0 {
		t.Errorf("got %v, want none", profiles)
	}
}

