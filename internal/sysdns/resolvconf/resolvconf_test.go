func TestParseResolved(t *testing.T) {
	out := `Link 2 (eth0): 192.168.1.5
              Current Scopes: DNS
              Current DNS Server: 169.254.20.10
              DNS Servers: 192.168.1.1
                           fd00::5
              DNS Domain: lan
`
	cfg := parseResolved(out)
	if len(cfg.Servers) != 2 {
		t.Fatalf("got %v, want two servers", cfg.Servers)
	}
	if cfg.Servers[0].String() != "192.168.1.1" || cfg.Servers[1].String() != "fd00::5" {
		t.Errorf("servers = %v", cfg.Servers)
	}
	// The synthetic address is not a resolver and must not appear.
	for _, s := range cfg.Servers {
		if s.String() == "169.254.20.10" {
			t.Error("the synthetic current-DNS-server address must be left out")
		}
	}
}

