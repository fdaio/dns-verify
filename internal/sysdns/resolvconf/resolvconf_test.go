package resolvconf

import (
	"os"
	"path/filepath"
	"testing"

	"net/netip"
)

func write(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
}

// A resolver file is the base on every Linux system, whatever wrote it.
func TestReadFile(t *testing.T) {
	cases := []struct {
		name    string
		content string
		servers []string
		search  []string
	}{
		{
			name: "docker injected",
			content: `# Generated by Docker Engine.

nameserver 0.250.250.200

# Based on host file
`,
			servers: []string{"0.250.250.200"},
		},
		{
			name: "systemd resolved stub",
			content: `nameserver 127.0.0.53
options edns0 trust-ad
search lan example.lan
`,
			servers: []string{"127.0.0.53"},
			search:  []string{"lan", "example.lan"},
		},
		{
			name:    "several servers",
			content: "nameserver 1.1.1.1\nnameserver 8.8.8.8\nnameserver 9.9.9.9\n",
			servers: []string{"1.1.1.1", "8.8.8.8", "9.9.9.9"},
		},
		{
			name:    "comments stripped",
			content: "nameserver 1.1.1.1 # the primary\n# nameserver 8.8.8.8\n",
			servers: []string{"1.1.1.1"},
		},
		{
			name:    "malformed address skipped",
			content: "nameserver not-an-address\nnameserver 1.1.1.1\n",
			servers: []string{"1.1.1.1"},
		},
		{
			name:    "domain is a search alias",
			content: "domain example.lan\nnameserver 192.168.1.1\n",
			servers: []string{"192.168.1.1"},
			search:  []string{"example.lan"},
		},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), "resolv.conf")
			write(t, path, c.content)

			cfg, err := ReadFile(path)
			if err != nil {
				t.Fatalf("ReadFile: %v", err)
			}
			if got := len(cfg.Servers); got != len(c.servers) {
				t.Fatalf("got %d servers (%v), want %d", got, cfg.Servers, len(c.servers))
			}
			for i, want := range c.servers {
				if cfg.Servers[i].String() != want {
					t.Errorf("server %d = %v, want %v", i, cfg.Servers[i], want)
				}
			}
			if len(c.search) > 0 {
				if len(cfg.Search) != len(c.search) {
					t.Fatalf("search = %v, want %v", cfg.Search, c.search)
				}
				for i, want := range c.search {
					if cfg.Search[i] != want {
						t.Errorf("search %d = %q, want %q", i, cfg.Search[i], want)
					}
				}
			}
		})
	}
}

// A lone stub address is a door to another resolver, so it is recorded apart
// from the resolvers a query actually reaches.
func TestStubIsRecordedApart(t *testing.T) {
	for _, addr := range []string{"127.0.0.53", "0.250.250.200", "127.0.0.1"} {
		path := filepath.Join(t.TempDir(), "resolv.conf")
		write(t, path, "nameserver "+addr+"\n")

		cfg, err := ReadFile(path)
		if err != nil {
			t.Fatalf("ReadFile: %v", err)
		}
		if !cfg.Stub.IsValid() || cfg.Stub.String() != addr {
			t.Errorf("%s: stub = %v, want %s", addr, cfg.Stub, addr)
		}
	}
}

// Two real resolvers are not a door; both answer.
func TestTwoServersAreNotAStub(t *testing.T) {
	path := filepath.Join(t.TempDir(), "resolv.conf")
	write(t, path, "nameserver 127.0.0.53\nnameserver 1.1.1.1\n")

	cfg, err := ReadFile(path)
	if err != nil {
		t.Fatalf("ReadFile: %v", err)
	}
	if cfg.Stub.IsValid() {
		t.Errorf("stub = %v, want none with two servers", cfg.Stub)
	}
}

func TestIsStub(t *testing.T) {
	cases := []struct {
		addr string
		want bool
	}{
		{"127.0.0.53", true},
		{"127.0.0.1", true},
		{"0.250.250.200", true},
		{"0.0.0.0", true},
		{"1.1.1.1", false},
		{"192.168.1.1", false},
		{"10.206.0.2", false},
		{"fd00::1", false},
		{"::1", false},
	}
	for _, c := range cases {
		got := IsStub(netip.MustParseAddr(c.addr))
		if got != c.want {
			t.Errorf("IsStub(%s) = %v, want %v", c.addr, got, c.want)
		}
	}
}

// The managed paths are rewritten on every boot, so a resolver there was not
// chosen by anyone.
// isManaged answers whether the network manager rewrites that path on every
// boot. The paths themselves are implementation detail, so the test pins the
// property: managed paths are managed, and nothing else is.
func TestManagedPathsAreNotConfigured(t *testing.T) {
	cases := []struct {
		path string
		want bool
	}{
		{"/run/systemd/resolve/stub-resolv.conf", true},
		{"/var/run/NetworkManager/resolv.conf", true},
		{"/run/resolvconf/resolv.conf", true},
		{"/run/systemd/resolve/resolv.conf", true},
		{"/etc/resolv.conf", false},
		{"/etc/resolvconf/resolv.conf.d/head", false},
		{"/tmp/resolv.conf", false},
	}
	for _, c := range cases {
		if got := isManaged(c.path); got != c.want {
			t.Errorf("isManaged(%q) = %v, want %v", c.path, got, c.want)
		}
	}
}

